import streamlit as st
import pandas as pd

def show_prediction_interface(df, feature_cols, numeric_cols, categorical_cols, results, problem_type):
    """Step: Let the user get predictions from the best-performing model."""
    st.header("Step 8: Predict with the Best Model")

    best_pipeline = results.get("best_pipeline")
    best_model_name = results.get("best_model_name")
    label_encoder = results.get("label_encoder")

    if best_pipeline is None:
        st.info("Train the models above first to unlock predictions.")
        return

    st.write(f"Enter new values below, and the platform will predict the outcome using {best_model_name} — the model that performed best during training.")

    feature_numeric = [c for c in feature_cols if c in numeric_cols]
    feature_categorical = [c for c in feature_cols if c in categorical_cols]

    tab1, tab2 = st.tabs(["Manual Input", "Batch Prediction (CSV)"])

    with tab1:
        st.write("Fill in a value for each feature below.")
        input_data = {}

        cols = st.columns(3)
        for i, feat in enumerate(feature_cols):
            col = cols[i % 3]
            if feat in feature_numeric:
                default_val = float(df[feat].median()) if df[feat].notna().any() else 0.0
                input_data[feat] = col.number_input(feat, value=default_val)
            else:
                options = df[feat].dropna().unique().tolist()
                input_data[feat] = col.selectbox(feat, options=options)

        if st.button("Predict", type="primary"):
            input_df = pd.DataFrame([input_data])
            try:
                prediction = best_pipeline.predict(input_df)
                if label_encoder is not None:
                    prediction = label_encoder.inverse_transform(prediction)

                st.success("Prediction complete.")
                st.metric("Predicted Result", str(prediction[0]))

                st.caption(
                    f"This prediction was generated by {best_model_name}, using the same preprocessing steps "
                    "(missing value handling, scaling, encoding) that were applied during training — this ensures "
                    "the input is treated exactly the same way the model learned from."
                )
            except Exception as e:
                st.error(f"Prediction failed: {e}")

    with tab2:
        st.write(f"Upload a CSV containing the same feature columns: {', '.join(feature_cols)}")
        batch_file = st.file_uploader("Upload CSV for batch prediction", type=["csv"], key="batch_predict")

        if batch_file is not None:
            batch_df = pd.read_csv(batch_file)
            missing_cols = [c for c in feature_cols if c not in batch_df.columns]

            if missing_cols:
                st.error(f"This file is missing required columns: {missing_cols}")
            else:
                try:
                    preds = best_pipeline.predict(batch_df[feature_cols])
                    if label_encoder is not None:
                        preds = label_encoder.inverse_transform(preds)

                    output_df = batch_df.copy()
                    output_df["Prediction"] = preds

                    st.success(f"Generated {len(preds)} predictions.")
                    st.dataframe(output_df, use_container_width=True)

                    csv_bytes = output_df.to_csv(index=False).encode("utf-8")
                    st.download_button(
                        "Download Predictions as CSV",
                        data=csv_bytes,
                        file_name="predictions.csv",
                        mime="text/csv"
                    )
                except Exception as e:
                    st.error(f"Batch prediction failed: {e}")